"use strict";
// Writes the size tables the app ships beside its prompt tokens (user decision 2026-11-25: the wording lives on the
// server; estimates of request size still need each prompt's length). Only byte counts leave the repository.
// Usage: node scripts/prompt-library-sync.cjs [--check]
const fs = require("node:fs");
const path = require("node:path");

const desktop = path.resolve(__dirname, "..");
const LIBRARY = path.resolve(desktop, "..", "server", "provider-gateway", "prompt-library.json");

function sizes(library = JSON.parse(fs.readFileSync(LIBRARY, "utf8"))) {
  return Object.fromEntries(Object.keys(library).sort().map((key) => [key, Buffer.byteLength(library[key], "utf8")]));
}

function outputs(table = sizes()) {
  const header = "Generated by scripts/prompt-library-sync.cjs from the server prompt library: byte sizes only, no wording.";
  const py = `"""${header}"""\nSIZES = ${JSON.stringify(table, null, 1)}\n`;
  const js = `"use strict";\n// ${header}\nmodule.exports = ${JSON.stringify(table, null, 1)};\n`;
  return {
    [path.join(desktop, "sidecars", "content-engine", "content_engine", "prompt_sizes.py")]: py,
    [path.join(desktop, "sidecars", "product-detail", "app", "prompt_sizes.py")]: py,
    [path.join(desktop, "src", "shared", "prompt-sizes.cjs")]: js
  };
}

module.exports = { sizes, outputs, LIBRARY };

if (require.main === module) {
  const stale = [];
  for (const [file, text] of Object.entries(outputs())) {
    // Line endings may differ after a Windows checkout; the content is what counts.
    const current = (fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "").replace(/\r\n/gu, "\n");
    if (current === text) continue;
    if (process.argv.includes("--check")) stale.push(path.relative(desktop, file));
    else fs.writeFileSync(file, text);
  }
  if (stale.length) { console.error(`prompt size tables out of date: ${stale.join(", ")} (run node scripts/prompt-library-sync.cjs)`); process.exit(1); }
  console.log("prompt size tables match the library");
}
